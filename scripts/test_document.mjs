import assert from 'node:assert/strict';
import { createEmptyProject } from '../packages/shared/dist/index.js';
import { documentState, documentReducer } from '../apps/web/src/lib/documentState.ts';
let state = documentState(createEmptyProject());
const edit = update => ({ type:'edit', generation:state.generation, update, at:'test' });
state = documentReducer(state, edit(p=>({...p,name:'edited'})));
assert.notEqual(state.revision,state.savedRevision);
const saved = {type:'saved',generation:state.generation,revision:state.revision};
state = documentReducer(state, edit(p=>({...p,name:'newer'})));
state = documentReducer(state,saved);
assert.notEqual(state.revision,state.savedRevision,'saving an old snapshot must not clear newer edits');
const late=edit(p=>({...p,name:'stale async result'}));
state=documentReducer(state,{type:'replace',project:createEmptyProject()});
assert.equal(state.revision,state.savedRevision);
assert.equal(documentReducer(state,late),state,'reject callbacks from previous document');
assert.equal(documentReducer(state,{type:'select',pageId:'missing'}),state);
const initial=state;
state=documentReducer(state,edit(p=>({...p,handwritingProfiles:[...p.handwritingProfiles,{id:'p1'}]})));
state=documentReducer(state,edit(p=>({...p,handwritingProfiles:[...p.handwritingProfiles,{id:'p2'}]})));
assert.equal(state.project.handwritingProfiles.length,2,'successive async mutations must merge latest content');
assert.equal(initial.project.handwritingProfiles.length,0,'previous snapshots remain immutable');
assert.equal(documentReducer(state,edit(p=>p)),state,'no-op preserves revision');
const restoredDraft=documentReducer(state,{type:'replace',project:createEmptyProject(),dirty:true});
assert.notEqual(restoredDraft.revision,restoredDraft.savedRevision,'restored drafts remain explicitly unsaved');
console.log('PASS: document revisions, stale generations, snapshot saves, concurrent updates and navigation');
const { appendGlyphs } = await import('../apps/web/src/lib/profileEdits.ts');
const profile={id:'p',sampleSets:[{id:'s'}],glyphs:[{char:'字',variantIndex:3}]};
let updated=appendGlyphs(profile,[{char:'字',sourceSampleSetId:'s',variantIndex:0}]);
updated=appendGlyphs(updated,[{char:'字',sourceSampleSetId:'s',variantIndex:0}]);
assert.deepEqual(updated.glyphs.map(g=>g.variantIndex),[3,4,5]);
assert.equal(appendGlyphs(profile,[{char:'字',sourceSampleSetId:'deleted'}]),profile);
console.log('PASS: concurrent glyph indices and deleted sample isolation');
