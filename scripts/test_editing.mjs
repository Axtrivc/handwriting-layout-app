import assert from 'node:assert/strict';
import { HistoryStore } from '../apps/web/src/lib/historyStore.ts';
import { clipSelection } from '../apps/web/src/lib/cleanSelection.ts';
const history = new HistoryStore();
const a = [{ text: 'A', style: { size: 12 } }];
history.push('p1', []);
assert.deepEqual(history.undo('p1', a), [], 'first edit must undo');
assert.deepEqual(history.redo('p1', []), a, 'latest edit must redo');
history.push('p1', a);
const b = [{ text: 'B' }];
assert.deepEqual(history.undo('p1', b), a, 'undo one step, not two');
assert.deepEqual(history.undo('p1', a), []);
assert.deepEqual(history.redo('p1', []), a);
history.push('p1', a);
assert.equal(history.canRedo('p1'), false, 'editing discards redo');
assert.equal(history.undo('p2', []), null, 'pages are isolated');
a[0].style.size = 99;
assert.equal(history.undo('p1', b)[0].style.size, 12, 'snapshots are independent');
history.clear();
assert.equal(history.canUndo('p1'), false);
assert.deepEqual(clipSelection({x:-2.5,y:10.2,width:20,height:10},100,100),{x:0,y:10,width:18,height:11});
assert.deepEqual(clipSelection({x:90,y:90,width:30,height:30},100,100),{x:90,y:90,width:10,height:10});
assert.equal(clipSelection({x:120,y:5,width:10,height:10},100,100),null);
assert.deepEqual(clipSelection({x:20,y:20,width:-10,height:-10},100,100),{x:10,y:10,width:10,height:10});
assert.equal(clipSelection({x:NaN,y:5,width:10,height:10},100,100),null);
console.log('PASS: undo/redo, page isolation, snapshot copies, selection clipping');
